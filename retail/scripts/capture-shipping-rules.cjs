function capture(name, context, attribute, operator, value, expected, some = false) {
  const rules = attribute === null ? [] : [{ attribute, operator, value }]
  const normalized = structuredClone(rules)
  validateAndNormalizeRules(normalized)
  const actual = isContextValid(context, normalized, { someAreValid: some })
  assert.equal(actual, expected, name)
  rows.push({ name, context, rules, some, expected: actual })
}
